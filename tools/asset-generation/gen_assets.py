#!/usr/bin/env python3
"""HUSH asset generator.

Rasterises the fonts, title logo and the satirical advertising panels into
PSP-ready RGBA4444 textures and writes them as C headers in
src/assets/generated/. Everything drawn here is original; the only third-party
inputs are two freely licensed typefaces (DejaVu Sans Mono - Bitstream Vera
licence; Inter - SIL Open Font License 1.1), see LICENSE.

usage: python3 tools/asset-generation/gen_assets.py [--preview DIR]
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont, ImageFilter

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'src', 'assets', 'generated')
MONO = '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf'
MONO_B = '/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf'
INTER = '/usr/share/fonts/opentype/inter/Inter-Medium.otf'
INTER_THIN = '/usr/share/fonts/opentype/inter/InterDisplay-ExtraLight.otf'
INTER_LIGHT = '/usr/share/fonts/opentype/inter/Inter-Light.otf'
INTER_BOLD = '/usr/share/fonts/opentype/inter/Inter-SemiBold.otf'

FIRST, LAST = 32, 126


def to4444(img):
    """RGBA PIL image -> list of u16 in PSP GU_PSM_4444 layout (ABGR nibbles: a<<12|b<<8|g<<4|r)."""
    px = img.convert('RGBA').load()
    w, h = img.size
    out = []
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            out.append(((a >> 4) << 12) | ((b >> 4) << 8) | ((g >> 4) << 4) | (r >> 4))
    return out


def write_header(name, w, h, data, extra=''):
    path = os.path.join(OUT, name + '.h')
    with open(path, 'w') as f:
        f.write('/* Generated by tools/asset-generation/gen_assets.py - do not edit. */\n')
        f.write('#pragma once\n#include <stdint.h>\n')
        f.write(f'#define {name.upper()}_W {w}\n#define {name.upper()}_H {h}\n')
        f.write(extra)
        f.write(f'static const uint16_t __attribute__((aligned(16))) {name}_tex[{w * h}] = {{\n')
        for i in range(0, len(data), 16):
            f.write('  ' + ','.join(f'0x{v:04x}' for v in data[i:i + 16]) + ',\n')
        f.write('};\n')
    return path


def font_atlas(name, font_path, size, tw, th, mono, pad=1, stroke=0):
    font = ImageFont.truetype(font_path, size)
    ascent, descent = font.getmetrics()
    cell_h = ascent + descent
    img = Image.new('RGBA', (tw, th), (255, 255, 255, 0))
    d = ImageDraw.Draw(img)
    x, y = 0, 0
    glyphs = []
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        adv = int(round(font.getlength(ch)))
        bw = adv + 2 * pad
        if x + bw > tw:
            x = 0
            y += cell_h + pad
        if y + cell_h > th:
            raise SystemExit(f'{name}: atlas too small')
        d.text((x + pad, y), ch, font=font, fill=(255, 255, 255, 255), stroke_width=stroke, stroke_fill=(255, 255, 255, 255))
        glyphs.append((x, y, bw, adv))
        x += bw
    extra = f'#define {name.upper()}_LINE {cell_h}\n#define {name.upper()}_PAD {pad}\n'
    extra += f'static const uint16_t {name}_glyphs[{len(glyphs)}][4] = {{\n'
    extra += ''.join(f'  {{{g[0]},{g[1]},{g[2]},{g[3]}}},\n' for g in glyphs) + '};\n'
    return img, extra


def logo():
    """The HUSH wordmark: wide-tracked thin capitals over a faint scan line."""
    w, h = 256, 64
    img = Image.new('RGBA', (w, h), (255, 255, 255, 0))
    d = ImageDraw.Draw(img)
    font = ImageFont.truetype(INTER_THIN, 54)
    letters = 'HUSH'
    track = 22
    widths = [font.getlength(c) for c in letters]
    total = sum(widths) + track * (len(letters) - 1)
    x = (w - total) / 2
    for c, cw in zip(letters, widths):
        d.text((x, 0), c, font=font, fill=(255, 255, 255, 255))
        x += cw + track
    d.line([(24, 60), (w - 24, 60)], fill=(255, 255, 255, 90), width=1)
    return img


def credit():
    w, h = 256, 16
    img = Image.new('RGBA', (w, h), (255, 255, 255, 0))
    d = ImageDraw.Draw(img)
    font = ImageFont.truetype(INTER_LIGHT, 12)
    text = 'b y   S y n t h   C e n t r i c'
    tw = font.getlength(text)
    d.text(((w - tw) / 2, 1), text, font=font, fill=(255, 255, 255, 255))
    return img


# Satirical billboards. (headline, small print, accent colour, motif)
ADS = [
    ('SILENCE', 'NOW BY SUBSCRIPTION', (120, 200, 255), 'rings'),
    ('MNEMOCORP', 'YOUR MEMORIES, INSURED', (255, 170, 80), 'eye'),
    ('YOU ARE CALM', 'WELLBEING BROADCAST 24/7', (170, 255, 210), 'wave'),
    ('RAINFALL®', 'PROPERTY OF WEATHERHOLD', (150, 150, 255), 'rain'),
    ('FEEL WHAT', 'WE PREDICT FOR YOU', (255, 110, 160), 'bars'),
    ('QUIETZONE+', '4.99 / HOUR OF QUIET', (110, 230, 255), 'rings'),
    ('REGISTER', 'YOUR MELODIES TODAY', (255, 200, 90), 'notes'),
    ('THE ARCHIVE', 'WE REMEMBER YOU', (220, 220, 230), 'grid'),
    ('ALLOWANCE', 'SILENCE: 6H DAILY', (255, 150, 90), 'bars'),
    ('REPORT', 'UNLICENSED SONG', (255, 90, 90), 'eye'),
    ('SLEEP+', 'PREMIUM DARKNESS', (160, 130, 255), 'wave'),
    ('BE HEARD', 'BE BILLED', (120, 255, 200), 'notes'),
]


def ad_panel(head, small, col, motif):
    w, h = 128, 64
    img = Image.new('RGBA', (w, h), (8, 10, 16, 255))
    d = ImageDraw.Draw(img)
    c2 = tuple(int(v * 0.35) for v in col)
    # motif on the left
    if motif == 'rings':
        for r in range(4, 26, 5):
            d.ellipse([16 - r, 32 - r, 16 + r, 32 + r], outline=c2 + (255,))
    elif motif == 'eye':
        d.ellipse([3, 20, 31, 44], outline=col + (255,))
        d.ellipse([12, 27, 22, 37], fill=col + (255,))
    elif motif == 'wave':
        pts = [(x, 32 + int(9 * __import__('math').sin(x / 3.0))) for x in range(2, 32)]
        d.line(pts, fill=col + (255,), width=2)
    elif motif == 'rain':
        for i in range(12):
            x = 3 + (i * 7) % 28
            y = 6 + (i * 13) % 44
            d.line([(x, y), (x - 2, y + 8)], fill=col + (255,))
    elif motif == 'bars':
        for i in range(6):
            bh = 6 + (i * 17) % 30
            d.rectangle([3 + i * 5, 52 - bh, 6 + i * 5, 52], fill=col + (255,))
    elif motif == 'notes':
        for i in range(3):
            x = 5 + i * 9
            y = 22 + (i % 2) * 8
            d.ellipse([x, y + 12, x + 6, y + 17], fill=col + (255,))
            d.line([(x + 6, y), (x + 6, y + 14)], fill=col + (255,), width=1)
    else:
        for i in range(0, 30, 6):
            d.line([(2 + i, 10), (2 + i, 54)], fill=c2 + (255,))
            d.line([(2, 10 + i * 1.4), (32, 10 + i * 1.4)], fill=c2 + (255,))
    fh = ImageFont.truetype(INTER_BOLD, 15)
    while fh.getlength(head) > 88 and fh.size > 9:
        fh = ImageFont.truetype(INTER_BOLD, fh.size - 1)
    fs = ImageFont.truetype(INTER, 8)
    while fs.getlength(small) > 88 and fs.size > 5:
        fs = ImageFont.truetype(INTER, fs.size - 1)
    d.text((36, 17), head, font=fh, fill=col + (255,))
    d.text((37, 38), small, font=fs, fill=(200, 205, 215, 255))
    d.rectangle([0, 0, w - 1, h - 1], outline=c2 + (255,))
    return img


def main():
    os.makedirs(OUT, exist_ok=True)
    preview = None
    if len(sys.argv) > 2 and sys.argv[1] == '--preview':
        preview = sys.argv[2]
        os.makedirs(preview, exist_ok=True)
    small, ex = font_atlas('font_small', MONO, 11, 256, 64, True)
    write_header('font_small', 256, 64, to4444(small), ex)
    large, ex = font_atlas('font_large', INTER, 17, 256, 128, False)
    write_header('font_large', 256, 128, to4444(large), ex)
    lg = logo()
    write_header('logo', 256, 64, to4444(lg))
    cr = credit()
    write_header('credit', 256, 16, to4444(cr))
    sheet = Image.new('RGBA', (256, 512), (0, 0, 0, 255))  # GE textures must be power-of-two sized
    for i, a in enumerate(ADS):
        sheet.paste(ad_panel(*a), ((i % 2) * 128, (i // 2) * 64))
    write_header('ads', 256, 512, to4444(sheet), f'#define ADS_COUNT {len(ADS)}\n')
    if preview:
        for n, im in [('font_small', small), ('font_large', large), ('logo', lg), ('credit', cr), ('ads', sheet)]:
            bg = Image.new('RGBA', im.size, (20, 24, 32, 255))
            bg.alpha_composite(im)
            bg.save(os.path.join(preview, n + '.png'))
    print('assets written to', OUT)


if __name__ == '__main__':
    main()
